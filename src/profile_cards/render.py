"""Render every card and the README from a config and a snapshot."""

from __future__ import annotations

from urllib.parse import quote

from profile_cards.cards import activity, heatmap, hero, projects, upstream
from profile_cards.config import Config
from profile_cards.model import Snapshot
from profile_cards.theme import esc, fmt_int

CARDS_DIR = "cards"
README_NAME = "README.md"
GITHUB = "https://github.com"


def _img(name: str, alt: str, width: str = "100%") -> str:
    return f'<img src="./{CARDS_DIR}/{name}" width="{width}" alt="{esc(alt)}" />'


def _merged_search_url(login: str) -> str:
    query = quote(f"author:{login} is:pr is:merged -user:{login}")
    return f"{GITHUB}/search?q={query}&type=pullrequests"


def render_readme(config: Config, snapshot: Snapshot) -> str:
    months = 24 if snapshot.has_previous_year else 12
    rows = [
        f'<a href="{esc(config.site_url)}">'
        + _img(
            "hero.svg",
            f"{config.name}, {config.role} in {config.location}. {config.tagline}",
        )
        + "</a>",
        _img(
            "heatmap.svg",
            f"Every day, in blue: {fmt_int(snapshot.total)} contributions over a year.",
        ),
        _img(
            "activity.svg",
            f"The last {months} months on GitHub: monthly totals, streaks and "
            "weekday rhythm.",
        ),
        f'<a href="{esc(_merged_search_url(config.login))}">'
        + _img(
            "upstream.svg",
            f"{snapshot.upstream.merged_prs} merged and {snapshot.upstream.open_prs} "
            "open pull requests in other people's projects.",
        )
        + "</a>",
        _img("coding.svg", "What I'm coding right now."),
    ]
    project_row = "".join(
        f'<a href="{GITHUB}/{esc(project.repo)}">'
        + _img(f"project-{i}.svg", f"{project.name}: {project.blurb}", "33.333%")
        + "</a>"
        for i, project in enumerate(snapshot.projects, start=1)
    )
    links = " &nbsp;/&nbsp; ".join(
        f'<a href="{esc(link.url)}">{esc(link.label)}</a>' for link in config.links
    )
    cards = "<br>\n".join([*rows, project_row])
    return (
        "<!-- Generated by `profile-cards render`; "
        "edit config.toml, not this file. -->\n"
        f'<div align="center">\n{cards}\n</div>\n\n'
        f'<p align="center">\n{links}\n</p>\n'
    )


def render_all(config: Config, snapshot: Snapshot) -> dict[str, str]:
    """Map each output path (relative to the repository root) to its content."""
    files = {
        f"{CARDS_DIR}/hero.svg": hero.render(config, snapshot),
        f"{CARDS_DIR}/heatmap.svg": heatmap.render(config, snapshot),
        f"{CARDS_DIR}/activity.svg": activity.render(config, snapshot),
        f"{CARDS_DIR}/upstream.svg": upstream.render(config, snapshot),
        f"{CARDS_DIR}/coding.svg": projects.render_title(config, snapshot),
        README_NAME: render_readme(config, snapshot),
    }
    for index, project in enumerate(snapshot.projects, start=1):
        files[f"{CARDS_DIR}/project-{index}.svg"] = projects.render_project(
            config, project, index
        )
    return files
